/**
 * Build step 1: snapshot the published content for the prerender.
 *
 * Reads Neon with the read-only role (DATABASE_URL_BUILD). Without it (local development, CI)
 * it falls back to scripts/seed.json; with it set but unreachable, the build fails rather than
 * publish seed content over the client's.
 *
 * Writes:
 *   src/lib/generated/content.json   published content, mapped for the public components
 *   src/lib/generated/media.json     every image in use, for build-images.ts
 *   src/lib/generated/build.json     build id, publish id, site URL, noindex flag
 *   static/build-info.json           the same ids, polled by the CMS after Publiceren
 *   _redirects                       from the redirects table (the adapter copies it)
 */
import './lib/env';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { and, desc, eq, inArray, lte } from 'drizzle-orm';
import { mapContent, type Rows } from '../src/lib/server/content-map';
import { loadRows } from '../src/lib/server/content-rows';
import { createNodeDb } from '../src/lib/server/db/client-node';
import * as t from '../src/lib/server/db/schema';
import type { Img, SiteContent } from '../src/lib/types';

const started = new Date();
// Pull-request previews read the shared Neon `dev` branch (DATABASE_URL_BUILD_PREVIEW), never main.
const isPreview = !!process.env.WORKERS_CI_BRANCH && process.env.WORKERS_CI_BRANCH !== 'main';
const dbUrl = (isPreview && process.env.DATABASE_URL_BUILD_PREVIEW) || process.env.DATABASE_URL_BUILD;
if (isPreview && process.env.DATABASE_URL_BUILD && !process.env.DATABASE_URL_BUILD_PREVIEW)
	throw new Error('Preview build without DATABASE_URL_BUILD_PREVIEW: refusing to read the production branch.');
let rows: Rows;
let seedFiles: Record<string, string> = {};
let publishId: string | null = null;

if (dbUrl) {
	const { db, close } = createNodeDb(dbUrl);
	rows = await loadRows(db, true);
	// Claim the newest publish request that is waiting for a build.
	const [pending] = await db
		.select()
		.from(t.builds)
		.where(and(inArray(t.builds.status, ['pending', 'building']), lte(t.builds.triggeredAt, started)))
		.orderBy(desc(t.builds.triggeredAt))
		.limit(1);
	if (pending) {
		publishId = pending.id;
		await db
			.update(t.builds)
			.set({ status: 'building', buildUuid: process.env.WORKERS_CI_BUILD_UUID ?? null })
			.where(eq(t.builds.id, pending.id));
	}
	await close();
	console.log(`Content read from the database (${rows.projects.length} published projects).`);
} else {
	const seed = JSON.parse(await readFile('scripts/seed.json', 'utf8')) as { rows: Rows; files: Record<string, string> };
	rows = seed.rows;
	seedFiles = seed.files;
	console.log('DATABASE_URL_BUILD is not set: using scripts/seed.json.');
}

const content: SiteContent = mapContent(rows, { images: 'build', drafts: false });

// Every image the published content uses.
const used = new Set<string>();
const collect = (i: Img | null | undefined) => i && used.add(i.id);
content.pages.forEach((p) => collect(p.hero));
content.services.forEach((s) => collect(s.hero));
content.projects.forEach((p) => [p.cover, p.before, p.after, ...p.gallery].forEach(collect));
content.reviews.forEach((r) => collect(r.photo));
content.posts.forEach((p) => collect(p.cover));
const media = rows.media
	.filter((m) => used.has(m.id))
	.map((m) => ({ id: m.id, objectKey: m.objectKey, width: m.width, height: m.height, seedFile: seedFiles[m.id] ?? null }));

const siteUrl = (process.env.PUBLIC_SITE_URL ?? 'http://localhost:4173').replace(/\/$/, '');
const noindex =
	process.env.SITE_NOINDEX === '1' || (process.env.SITE_NOINDEX !== '0' && !/tnlgroup\.be$/.test(new URL(siteUrl).hostname));
const buildId = process.env.WORKERS_CI_BUILD_UUID ?? `local-${started.getTime().toString(36)}`;
const build = {
	buildId,
	publishId,
	builtAt: started.toISOString(),
	commit: process.env.WORKERS_CI_COMMIT_SHA ?? null,
	branch: process.env.WORKERS_CI_BRANCH ?? null,
	siteUrl,
	noindex,
	turnstileSiteKey: process.env.TURNSTILE_SITE_KEY ?? ''
};

await mkdir('src/lib/generated', { recursive: true });
await writeFile('src/lib/generated/content.json', JSON.stringify(content));
await writeFile('src/lib/generated/media.json', JSON.stringify(media, null, '\t'));
await writeFile('src/lib/generated/build.json', JSON.stringify(build, null, '\t'));
await writeFile(
	'static/build-info.json',
	JSON.stringify({ buildId, publishId, builtAt: build.builtAt, commit: build.commit }) + '\n'
);

const redirectLines = content.redirects.map((r) => `${r.fromPath} ${r.toPath} ${r.status}`);
await writeFile(
	'_redirects',
	['# Generated by scripts/build-content.ts from the redirects table. Do not edit.', ...redirectLines, ''].join('\n')
);

console.log(
	`build ${buildId}${publishId ? ` (publish ${publishId})` : ''}: ${media.length} images, ${redirectLines.length} redirects, noindex=${noindex}`
);
